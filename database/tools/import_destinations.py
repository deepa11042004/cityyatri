"""
Club Yatri - one-off destinations import.

Reads export/destinations.csv + export/destination-images.zip and produces:
  * assets/images/destinations/<slug>.webp      resized hero photo per destination
  * database/migrations/002_destinations.sql    CREATE TABLE + INSERTs (safe to re-run)

Hotels are linked to destinations by name (hotels.location_name = destinations.name).

Usage (from the project root):  python database/tools/import_destinations.py
"""
import csv
import io
import sys
import zipfile
from pathlib import Path

from PIL import Image, ImageOps

sys.path.insert(0, str(Path(__file__).resolve().parent))
from import_hotels import sql_str  # noqa: E402  (shared SQL string escaping)

ROOT = Path(__file__).resolve().parents[2]
CSV_PATH = ROOT / 'export' / 'destinations.csv'
ZIP_PATH = ROOT / 'export' / 'destination-images.zip'
IMG_DIR = ROOT / 'assets' / 'images' / 'destinations'
SQL_PATH = ROOT / 'database' / 'migrations' / '002_destinations.sql'

MAX_EDGE = 1400
WEBP_QUALITY = 76

DDL = """CREATE TABLE IF NOT EXISTS `destinations` (
  `id` INT UNSIGNED NOT NULL PRIMARY KEY,
  `slug` VARCHAR(160) NOT NULL UNIQUE,
  `name` VARCHAR(160) NOT NULL,
  `region` VARCHAR(80) DEFAULT NULL,
  `country` VARCHAR(80) NOT NULL,
  `location_type` ENUM('DOMESTIC', 'INTERNATIONAL') NOT NULL,
  `tagline` VARCHAR(255) DEFAULT NULL,
  `description` TEXT DEFAULT NULL,
  `highlights` TEXT DEFAULT NULL,
  `best_time` VARCHAR(255) DEFAULT NULL,
  `meta_title` VARCHAR(255) DEFAULT NULL,
  `meta_description` VARCHAR(500) DEFAULT NULL,
  `hero_image` VARCHAR(255) DEFAULT NULL,
  `source_url` VARCHAR(500) DEFAULT NULL,
  `featured` TINYINT(1) NOT NULL DEFAULT 0,
  `is_published` TINYINT(1) NOT NULL DEFAULT 1,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  KEY `idx_destinations_type` (`location_type`, `is_published`),
  KEY `idx_destinations_name` (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
"""


def flag(value: str) -> str:
    return '1' if value.strip().lower() == 'true' else '0'


def main():
    rows = [r for r in csv.DictReader(open(CSV_PATH, encoding='utf-8-sig', newline='')) if r['slug'].strip()]
    z = zipfile.ZipFile(ZIP_PATH)
    members = {}
    for n in z.namelist():
        if not n.endswith('/'):
            folder, _, fn = n.rpartition('/')
            members[(folder, fn)] = n
            members.setdefault(('*', fn), n)

    IMG_DIR.mkdir(parents=True, exist_ok=True)
    values, missing, failed = [], [], []
    total = 0

    for idx, r in enumerate(rows, start=1):
        slug = r['slug'].strip()
        fn = r['heroImageUrl'].strip().rsplit('/', 1)[-1]
        member = members.get((r['name'].strip(), fn)) or members.get(('*', fn))
        hero = None
        if not fn or member is None:
            missing.append(slug)
        else:
            dest = IMG_DIR / f'{slug}.webp'
            try:
                if not dest.exists():
                    with Image.open(io.BytesIO(z.read(member))) as im:
                        im = ImageOps.exif_transpose(im).convert('RGB')
                        im.thumbnail((MAX_EDGE, MAX_EDGE), Image.LANCZOS)
                        im.save(dest, 'WEBP', quality=WEBP_QUALITY, method=4)
                total += dest.stat().st_size
                hero = f'assets/images/destinations/{slug}.webp'
            except Exception as exc:
                failed.append(f'{slug}: {exc}')

        highlights = '; '.join(h.strip() for h in r['highlights'].split(';') if h.strip())
        values.append('(' + ', '.join([
            str(idx), sql_str(slug), sql_str(r['name'].strip()), sql_str(r['region'].strip()),
            sql_str(r['country'].strip()), sql_str(r['type'].strip()), sql_str(r['tagline'].strip()),
            sql_str(r['description'].strip()), sql_str(highlights), sql_str(r['bestTimeToVisit'].strip()),
            sql_str(r['metaTitle'].strip()), sql_str(r['metaDescription'].strip()), sql_str(hero),
            sql_str(r['sourceUrl'].strip()), flag(r['featured']), flag(r['isPublished']),
        ]) + ')')

    cols = ('id, slug, name, region, country, location_type, tagline, description, highlights, best_time, '
            'meta_title, meta_description, hero_image, source_url, featured, is_published')
    upd = ', '.join(f'{c}=VALUES({c})' for c in cols.split(', ')[1:])

    with open(SQL_PATH, 'w', encoding='utf-8', newline='\n') as f:
        f.write('-- Club Yatri destinations import (generated by database/tools/import_destinations.py)\n')
        f.write('-- Safe to re-run. Applied automatically on deploy by deploy-migrate.php.\n')
        f.write('SET NAMES utf8mb4;\n\n')
        f.write(DDL + '\n')
        for i in range(0, len(values), 40):
            f.write(f'INSERT INTO `destinations` ({cols}) VALUES\n' + ',\n'.join(values[i:i + 40])
                    + f'\nON DUPLICATE KEY UPDATE {upd};\n\n')

    print(f'destinations: {len(rows)}  photos: {len(rows) - len(missing) - len(failed)}  size: {total / 1e6:.1f} MB')
    print('missing photos:', missing)
    print('failed:', failed)


if __name__ == '__main__':
    sys.exit(main())
